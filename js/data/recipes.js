/** Search links for foods without a built-in recipe (plain URLs, no API). */
export function recipeLinks(name) {
  const q = encodeURIComponent(`מתכון ${name}`);
  return [
    { id: "mako", title: "מאקו אוכל", url: `https://www.mako.co.il/search?q=${q}` },
    { id: "google", title: "גוגל", url: `https://www.google.com/search?q=${q}` },
    { id: "youtube", title: "יוטיוב", url: `https://www.youtube.com/results?search_query=${q}` },
  ];
}

/** Recipes for a food id: built-in ones, else 3 search links. */
export function recipesFor(foodId, name = "") {
  const recipes = RECIPES[foodId] ?? [];
  return recipes.length ? { recipes, links: [] } : { recipes: [], links: recipeLinks(name || foodId || "") };
}

export const findRecipe = (id) => Object.values(RECIPES).flat().find((r) => r.id === id) ?? null;
