// Regenerates js/sw-names.js (id -> [name, emoji]) from js/data/foods.js. The classic service worker cannot import ES modules.
// Run: node tools/gen-sw-names.mjs   (tests/push.test.js fails when the file is stale)
import { writeFileSync } from "node:fs";
import { FOODS } from "../js/data/foods.js";

const body = FOODS.map((f) => `  ${JSON.stringify(f[0])}: ${JSON.stringify([f[1], f[2]])},`).join("\n");
writeFileSync(new URL("../js/sw-names.js", import.meta.url), `// GENERATED by tools/gen-sw-names.mjs from js/data/foods.js. Do not edit by hand.\n// Classic script (no import/export): sw.js loads it with importScripts; tests import it for the global.\nglobalThis.WTE_FOOD_NAMES = {\n${body}\n};\n`);
